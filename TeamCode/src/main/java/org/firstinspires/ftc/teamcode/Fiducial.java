package org.firstinspires.ftc.teamcode;

public class Fiducial {
    public int id;
    public double x;
    public double y;
    public double z;

    public Fiducial() {
        id = 0;
        x = 0;
        y = 0;
        z = 0;
    }

    public Fiducial(int id) {
        this.id = id;
        x = 0;
        y = 0;
        z = 0;
    }
}